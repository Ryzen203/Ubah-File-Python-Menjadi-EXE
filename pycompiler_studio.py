    def poll(self):
        try:
            while True:
                msg = self.q.get_nowait()
                if msg[0] == "log":
                    self.log(msg[1])
                elif msg[0] == "done":
                    self.finish(msg[1], msg[2])
                elif msg[0] == "task_done":
                    self.task_finished(msg[1], msg[2])
                elif msg[0] == "scan":
                    if msg[1] == self._scan_seq:  # ignore stale scans
                        self.set_interps(msg[2], msg[3] if len(msg) > 3 else {})
        except queue.Empty:
            pass
        except Exception:
            log_error(traceback.format_exc())
        self.after(100, self.poll)

