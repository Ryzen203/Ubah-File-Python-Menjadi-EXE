"""
PyCompiler Studio - Python (.py) -> Windows (.exe) with a modern GUI.

* Targets Windows 7 (32/64-bit) up to Windows 11.
* Every Python lives in ONE fixed folder named "Python" that sits next to this app
  (created automatically). All runtimes inside it - at any sub-folder level - are
  detected and listed (name, version, bitness, PyInstaller and Tkinter status).
* Pythons installed on this PC (registry, PATH, common folders) are read too and listed FIRST;
  every list is sorted from the highest to the lowest version.
* Can write the "Details" tab of the EXE (version, company, description, language,
  product, copyright, website, comment) and set the EXE's "Date created".
* Installs/updates PyInstaller for a chosen runtime.
* Auto-detects required libraries from `import` statements, installs them into
  an isolated virtual environment, then builds with PyInstaller.
* Extracts a python.org installer you already have into the Python folder (the installer is
  never run in install mode; nothing is installed in Windows). The app downloads no Python.
* Bilingual UI: Indonesian / English.  Starts without a console window when
  launched through "PyCompiler Studio.pyw" (or pythonw.exe).

Run:  pip install customtkinter  &&  pythonw pycompiler_studio.py
"""
