def _pin_satisfied(pin, have):
    """True when the installed version `have` matches an `==` pin (supports '1.2.*' and local '+tags')."""
    if pin.endswith("*"):
        return have.startswith(pin[:-1])
    return have.split("+")[0] == pin.split("+")[0]


def missing_packages(requirements, installed):
    """The requirements that pip would still have to download/install.

    `installed` is the result of installed_packages() (None = unknown -> everything counts as missing).
    A requirement is satisfied when its name is installed and, if it is pinned with `==`, the
    installed version is that one. Other specifiers (>=, ~= ...) are judged by name only.
    """
    if installed is None:
        return list(requirements)
    out = []
    for req in requirements:
        m = re.match(r"\s*([A-Za-z0-9][A-Za-z0-9._-]*)", req)
        have = installed.get(normalize_pkg_name(m.group(1))) if m else None
        pin = re.search(r"==\s*([^\s,;]+)", req)
        if have is None or (pin and not _pin_satisfied(pin.group(1), have)):
            out.append(req)
    return out


def describe_runtime_folder(path):
    """One-line check of the files a python.exe needs next to it (for diagnostic messages)."""
    d = Path(path).parent
    try:
        size = f"{Path(path).stat().st_size // 1024} KB"
    except OSError:
        size = "?"
    try:
        dlls = sorted(f.name for f in d.glob("python3*.dll"))
    except OSError:
        dlls = []
    yes = lambda b: "ada" if b else "TIDAK ADA"
    return (f"python.exe {size}; python3x.dll: {', '.join(dlls) or 'TIDAK ADA'}; "
            f"vcruntime140.dll: {yes((d / 'vcruntime140.dll').is_file())}; Lib\\os.py: {yes((d / 'Lib' / 'os.py').is_file())}")


def probe_python(path, why=None):
    """Return {'path','ver','bits','tk','tkv','pyi'} for a python.exe, or None.

    When `why` (a list) is given and the probe fails, a short human-readable reason is appended.
    """
    reason = ""
    try:
        r = quiet_run([path, str(PROBE_FILE)], timeout=40, cwd=str(HOME))
        lines = r.stdout.strip().splitlines()
        if not lines:
            code = r.returncode & 0xFFFFFFFF
            tail = (r.stderr or "").strip().splitlines()
            reason = ("DLL tidak ditemukan (mis. python3x.dll / vcruntime140.dll); folder hasil ekstrak tidak lengkap "
                      "atau butuh VC++ Runtime" if code == 0xC0000135 else
                      f"kode keluar {r.returncode}" + (f": {tail[-1][:160]}" if tail else ""))
            raise ValueError(reason)
        d = json.loads(lines[-1])
        return {"path": str(path), "ver": tuple(int(x) for x in d["ver"]), "bits": int(d["bits"]),
                "tk": bool(d["tk"]), "tkv": d.get("tkv") or "", "pyi": d.get("pyi")}
    except Exception as e:
        if why is not None:
            text = reason or f"{type(e).__name__}: {e}"
            if isinstance(e, FileNotFoundError):
                text += " (Windows tidak bisa memulai file ini: DLL/komponen hilang, diblokir antivirus, atau folder tidak lengkap)"
            why.append(f"{text} | {describe_runtime_folder(path)}")
        return None


def merge_extracted(src, dst):
    """Merge an MSI administrative-extract folder into `dst` (the .msi/.cab copies at its root are skipped)."""
    src, dst = Path(src), Path(dst)
    dst.mkdir(parents=True, exist_ok=True)
    for item in src.iterdir():
        if item.is_dir():
            shutil.copytree(item, dst / item.name, dirs_exist_ok=True)
        elif item.suffix.lower() not in (".msi", ".cab"):
            shutil.copy2(item, dst / item.name)


# MSI components of the official installer that make up a stand-alone Python
# (interpreter, DLLs, standard library, Tcl/Tk + IDLE, Windows 7 C-runtime).
PORTABLE_MSIS = ("core", "exe", "lib", "tcltk", "ucrt")
LAYOUT_TIMEOUT = 90   # seconds to wait for `installer /layout` to finish writing its files
LAYOUT_POLL = 1.0


def find_msi(layout, name):
    """Locate <name>.msi anywhere below the /layout folder.

    The installer may put its MSI files in a sub-folder (e.g. 'amd64'); debug (_d) and
    symbol (_pdb) variants are ignored.
    """
    for pat in (f"{name}.msi", f"{name}_*.msi"):
        hits = sorted(h for h in Path(layout).rglob(pat)
                      if not h.stem.lower().endswith(("_d", "_pdb")))
        if hits:
            return hits[0]
    return None


def wait_for_layout(layout, name, timeout=None):
    """The bootstrapper can return before its files are fully written: wait until
    <name>.msi exists and the folder size stopped changing."""
    end = time.time() + (LAYOUT_TIMEOUT if timeout is None else timeout)
    last = -1
    while True:
        if find_msi(layout, name):
            size = sum(f.stat().st_size for f in Path(layout).rglob("*") if f.is_file())
            if size == last:
                return True
            last = size
        if time.time() >= end:
            return find_msi(layout, name) is not None
        time.sleep(LAYOUT_POLL)


def list_tree(root, limit=25):
    """Short listing of a folder (relative paths) for diagnostic log messages."""
    root = Path(root)
    items = sorted(str(f.relative_to(root)) for f in root.rglob("*") if f.is_file()) if root.is_dir() else []
    return ", ".join(items[:limit]) + (" …" if len(items) > limit else "") if items else "(kosong / empty)"

_SKIP_DIRS = {"scripts", "lib", "dlls", "include", "libs", "tcl", "doc", "tools", "__pycache__"}


DEEP_DEPTH, DEEP_LIMIT = 8, 6000   # fallback search: how deep / how many folders at most
SCAN_DEPTH = 6                     # normal search depth inside the Python folder


def scan_dir_for_pythons(root, depth=2, skip=True, limit=None):
    """Find python.exe files below `root` (at most `depth` folders deep); skips virtualenvs.

    skip=False also enters folders such as App/Tools (used by the deeper fallback search);
    `limit` caps the number of folders visited so a huge tree cannot freeze the scan.
    """
    found = []
    root = Path(root)
    if not root.is_dir():
        return found
    stack, visited = [(root, 0)], 0
    while stack:
        visited += 1
        if limit and visited > limit:
            break
        d, level = stack.pop()
        if (d / "pyvenv.cfg").exists():
            continue
        exe = d / "python.exe"
        if exe.is_file():
            found.append(str(exe))
            continue  # do not descend into an interpreter's own folders
        if level >= depth:
            continue
        try:
            for child in d.iterdir():
                if child.is_dir() and (not skip or child.name.lower() not in _SKIP_DIRS) \
                        and child.name.lower() not in ("__pycache__", "site-packages", "$recycle.bin"):
                    stack.append((child, level + 1))
        except OSError:
            pass
    return found


def runtime_sort_key(info):
    """Order of the runtime list: Pythons installed on the PC first, then those in the Python
    folder; inside each group the HIGHEST version first (64-bit before 32-bit on a tie)."""
    ver = tuple(info["ver"]) + (0,) * (3 - len(info["ver"]))
    return (0 if info.get("system") else 1, tuple(-x for x in ver), -info["bits"], str(info["path"]).lower())


def guess_version_from_path(path):
    """Best-effort (3, minor[, patch]) read from a folder name such as 'Python-3.8.10-x86' or
    'Python312'; looks at the folders above python.exe until one matches. None when unknown.
    Only used to order interpreters that cannot be run (their real version is unknown)."""
    from pathlib import PureWindowsPath
    for part in PureWindowsPath(str(path)).parent.parts[::-1][:5]:
        m = re.search(r"(?<![\d.])3[._ -]?(\d{1,2})(?:\.(\d+))?", part)
        if m:
            return (3, int(m.group(1))) + ((int(m.group(2)),) if m.group(2) else ())
    return None


def _is_venv_python(exe):
    p = Path(exe)
    return any((d / "pyvenv.cfg").is_file() for d in (p.parent, p.parent.parent))


def registry_pythons():
    """python.exe paths registered by python.org / PEP 514 installers (32- and 64-bit registry views)."""
    if os.name != "nt":
        return []
    try:
        import winreg
    except ImportError:
        return []
    found = []
    views = [0] + [getattr(winreg, n, 0) for n in ("KEY_WOW64_64KEY", "KEY_WOW64_32KEY")]
    for hive in (winreg.HKEY_LOCAL_MACHINE, winreg.HKEY_CURRENT_USER):
        for view in views:
            try:
                core = winreg.OpenKey(hive, r"SOFTWARE\Python\PythonCore", 0, winreg.KEY_READ | view)
            except OSError:
                continue
            with core:
                i = 0
                while True:
                    try:
                        tag = winreg.EnumKey(core, i)
                    except OSError:
                        break
                    i += 1
                    try:
                        with winreg.OpenKey(core, tag + r"\InstallPath", 0, winreg.KEY_READ | view) as key:
                            for value_name in ("ExecutablePath", ""):
                                try:
                                    val = str(winreg.QueryValueEx(key, value_name)[0]).strip().strip('"')
                                except OSError:
                                    continue
                                if not val:
                                    continue
                                exe = Path(val)
                                if exe.suffix.lower() == ".exe":
                                    exe = exe.with_name("python.exe")
                                else:
                                    exe = exe / "python.exe"
                                found.append(str(exe))
                    except OSError:
                        continue
    return found


def find_system_pythons():
    """python.exe of every Python installed on THIS PC (not inside the Python folder).

    Sources: Windows registry (python.org installers), common install folders, every folder on
    PATH, and the interpreter that runs this app. Virtual environments and the Microsoft Store
    "WindowsApps" stubs (which only open the Store) are skipped. Never raises.
    """
    cands = []
    try:
        cands += registry_pythons()
    except Exception:
        log_error(traceback.format_exc())
    env = os.environ
    bases = []
    if env.get("LOCALAPPDATA"):
        bases.append(Path(env["LOCALAPPDATA"]) / "Programs" / "Python")
    for var in ("ProgramFiles", "ProgramFiles(x86)", "ProgramW6432"):
        if env.get(var):
            bases.append(Path(env[var]))
    if env.get("SystemDrive"):
        bases.append(Path(env["SystemDrive"] + "\\"))
    for base in bases:
        try:
            cands += [str(h / "python.exe") for h in base.glob("Python*")]
        except OSError:
            pass
    cands += [os.path.join(d.strip().strip('"'), "python.exe") for d in env.get("PATH", "").split(os.pathsep) if d.strip()]
    if not getattr(sys, "frozen", False):
        cands.append(os.path.join(sys.base_prefix, "python.exe"))
    out, seen = [], set()
    for c in cands:
        try:
            key = os.path.normcase(os.path.abspath(c))
            if key in seen or "windowsapps" in key.lower() or not os.path.isfile(c) or _is_venv_python(c):
                continue
        except OSError:
            continue
        seen.add(key)
        out.append(os.path.abspath(c))
    return out


def discover_pythons(roots=(), extras=(), report=None):
    """Find every Python below `roots` (the fixed Python folder, any sub-folder level) and in `extras`.

    `extras` are Pythons found elsewhere on the PC (see find_system_pythons); they are flagged
    info["system"] = True unless they live inside one of the `roots`. The result is sorted with
    runtime_sort_key: PC-installed Pythons first, each group from the highest to the lowest version.

    `report` (optional dict) receives diagnostics: "roots" -> [(folder, exists, n_found)] and
    "failed" -> [(python.exe, reason)] for interpreters that were found but could not be run.
    """
    norm = lambda p: os.path.normcase(os.path.abspath(p))
    paths, root_keys = set(), []
    for r in roots:
        if r:
            root_keys.append(norm(r))
            hits = scan_dir_for_pythons(r, SCAN_DEPTH, limit=DEEP_LIMIT)
            if not hits and os.path.isdir(r):  # nothing close by: search much deeper before giving up
                hits = scan_dir_for_pythons(r, DEEP_DEPTH, skip=False, limit=DEEP_LIMIT)
                if hits and report is not None:
                    report.setdefault("deep", []).extend(hits)
            paths.update(hits)
            if report is not None:
                report.setdefault("roots", []).append((r, os.path.isdir(r), len(hits)))
    extra_paths = [e for e in extras if e and os.path.isfile(e)]
    extra_keys = {norm(e) for e in extra_paths}
    paths.update(extra_paths)

    unique = {}
    for p in sorted(paths, key=str.lower):
        unique.setdefault(norm(p), p)
    ensure_probe_script()
    reasons = {p: [] for p in unique.values()}
    with ThreadPoolExecutor(max_workers=4) as pool:
        infos = list(pool.map(lambda p: probe_python(p, reasons[p]), unique.values()))
    found = {}
    for path, info in zip(unique.values(), infos):
        if info:
            key = norm(path)
            info["system"] = key in extra_keys and not any(key.startswith(rk + os.sep) for rk in root_keys)
            found[os.path.normcase(info["path"])] = info
        elif report is not None:
            report.setdefault("failed", []).append((path, (reasons[path] or ["?"])[0]))
    return sorted(found.values(), key=runtime_sort_key)


