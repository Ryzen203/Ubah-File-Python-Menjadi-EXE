    def run(self, cmd, cwd=None):
        self.say("$ " + " ".join(f'"{c}"' if " " in str(c) else str(c) for c in cmd) + "\n")
        env = dict(os.environ, PYTHONIOENCODING="utf-8", PIP_DISABLE_PIP_VERSION_CHECK="1")
        p = subprocess.Popen([str(c) for c in cmd], cwd=cwd, env=env, stdout=subprocess.PIPE,
                             stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL, text=True,
                             encoding="utf-8", errors="replace", bufsize=1, creationflags=NO_WINDOW)
        self.proc = p
        try:
            for line in p.stdout:
                self.say(line)
            return p.wait()
        finally:
            self.proc = None

