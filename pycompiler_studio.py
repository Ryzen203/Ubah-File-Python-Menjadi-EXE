def parse_file_version(text):
    """'1.2' -> (1, 2, 0, 0); None unless the text is 1-4 dot separated numbers of 0..65535."""
    m = re.fullmatch(r"\s*(\d{1,5})(?:\.(\d{1,5}))?(?:\.(\d{1,5}))?(?:\.(\d{1,5}))?\s*", text or "")
    if not m:
        return None
    nums = tuple(int(g) if g else 0 for g in m.groups())
    return nums if max(nums) <= 65535 else None


def parse_created_date(text, now=None):
    """'' -> now; 'YYYY-MM-DD' -> that day at the current time of day; None when invalid (years 1980-2099)."""
    now = now or datetime.now()
    text = (text or "").strip()
    if not text:
        return now
    try:
        d = datetime.strptime(text, "%Y-%m-%d")
    except ValueError:
        return None
    if not 1980 <= d.year <= 2099:
        return None
    return d.replace(hour=now.hour, minute=now.minute, second=now.second)


def build_version_info(info, name, now=None):
    """Text of a PyInstaller --version-file (the EXE's Properties > Details tab).

    Empty optional fields are left out; description/product default to the app name and an
    empty copyright becomes "Copyright © <year> <company or product>". The website is stored
    as its own "Website" string and also appended to Comments (Explorer shows only Comments).
    Every value goes through ascii(), so any text is a safe Python literal.
    """
    nums = parse_file_version(info.get("version")) or (1, 0, 0, 0)
    ver = ".".join(map(str, nums))
    langid = dict(LANGUAGES).get(info.get("lang"), LANGUAGES[0][1])
    get = lambda k: (info.get(k) or "").strip()
    company, website = get("company"), get("website")
    product = get("product") or name
    year = (now or datetime.now()).year
    notice = get("copyright") or f"Copyright \u00a9 {year} {company or product}"
    comment = " | ".join(x for x in (get("comment"), website) if x)
    pairs = [("CompanyName", company), ("FileDescription", get("desc") or name), ("FileVersion", ver),
             ("InternalName", name), ("LegalCopyright", notice), ("OriginalFilename", name + ".exe"),
             ("ProductName", product), ("ProductVersion", ver), ("Comments", comment), ("Website", website)]
    structs = ", ".join(f"StringStruct({ascii(k)}, {ascii(v)})" for k, v in pairs if v)
    table = "%04X04B0" % langid
    return ("VSVersionInfo(\n"
            f"  ffi=FixedFileInfo(filevers={nums}, prodvers={nums}, mask=0x3f, flags=0x0, OS=0x40004,"
            " fileType=0x1, subtype=0x0, date=(0, 0)),\n"
            "  kids=[\n"
            f"    StringFileInfo([StringTable({ascii(table)}, [{structs}])]),\n"
            f"    VarFileInfo([VarStruct('Translation', [{langid}, 1200])])\n"
            "  ])\n")


def set_file_times(path, when):
    """Set Date created / modified / accessed of `path` to the datetime `when`.

    os.utime only reaches modified/accessed; the creation time needs SetFileTime (Windows).
    Returns False when the creation time could not be written.
    """
    ts = when.timestamp()
    os.utime(path, (ts, ts))
    if os.name != "nt":
        return True
    import ctypes
    from ctypes import wintypes
    k32 = ctypes.WinDLL("kernel32", use_last_error=True)
    k32.CreateFileW.restype = ctypes.c_void_p
    k32.CreateFileW.argtypes = [wintypes.LPCWSTR, wintypes.DWORD, wintypes.DWORD, ctypes.c_void_p,
                                wintypes.DWORD, wintypes.DWORD, ctypes.c_void_p]
    k32.SetFileTime.argtypes = [ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p, ctypes.c_void_p]
    k32.SetFileTime.restype = wintypes.BOOL
    k32.CloseHandle.argtypes = [ctypes.c_void_p]
    h = k32.CreateFileW(str(path), 0x100, 7, None, 3, 0x02000000, None)  # FILE_WRITE_ATTRIBUTES
    if h in (None, ctypes.c_void_p(-1).value):
        return False
    try:
        t = int((ts + 11644473600) * 10_000_000)  # Unix seconds -> 100 ns ticks since 1601
        ft = wintypes.FILETIME(t & 0xFFFFFFFF, t >> 32)
        return bool(k32.SetFileTime(h, ctypes.byref(ft), ctypes.byref(ft), ctypes.byref(ft)))
    finally:
        k32.CloseHandle(h)


def find_expand():
    """Windows' built-in expand.exe (unpacks .cab files); None when unavailable."""
    if os.name != "nt":
        return None
    exe = Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32" / "expand.exe"
    return str(exe) if exe.is_file() else shutil.which("expand")


def carve_cabs(path):
    """[(start, end)] of every top-level CAB archive appended to a WiX Burn bundle .exe.

    The official Python installer is a Burn bundle: its MSI files live in CAB containers
    attached to the .exe. A candidate must have a valid CFHEADER (signature, zero reserved
    field, version 1.3, size inside the file) and must not start inside a previous CAB.
    """
    data = Path(path).read_bytes()
    cabs, pos = [], 0
    while True:
        i = data.find(b"MSCF", pos)
        if i < 0:
            return cabs
        if i + 36 <= len(data) and data[i + 4:i + 8] == b"\0\0\0\0" and data[i + 24:i + 26] == b"\x03\x01":
            size = int.from_bytes(data[i + 8:i + 12], "little")
            if 36 < size <= len(data) - i:
                cabs.append((i, i + size))
                pos = i + size
                continue
        pos = i + 4


def burn_payloads(manifest):
    """[(FilePath, SourcePath)] of the embedded (non-UX) payloads listed in a Burn manifest (bytes/str)."""
    root = ET.fromstring(manifest)
    out = []
    for el in root.iter():
        if el.tag.rsplit("}", 1)[-1] != "Payload":
            continue
        if el.get("Packaging") == "embedded" and el.get("SourcePath") and el.get("FilePath") \
                and el.get("Container") != "WixUXContainer":
            out.append((el.get("FilePath"), el.get("SourcePath")))
    return out


def parse_installer_name(filename):
    """(version, bits) from an official installer name such as python-3.8.10.exe or
    python-3.12.10-amd64.exe; None when the name is not a python.org Windows installer."""
    m = re.fullmatch(r"python-(3\.\d{1,2}\.\d{1,2}(?:(?:a|b|rc)\d+)?)(-amd64)?\.exe", filename, re.I)
    return (m.group(1), 64 if m.group(2) else 32) if m else None


def verify_signature(path):
    """Authenticode status of a file via PowerShell ('Valid', 'HashMismatch', ...)."""
    if os.name != "nt":
        return "Skipped"
    try:
        r = quiet_run(["powershell", "-NoProfile", "-NonInteractive", "-ExecutionPolicy", "Bypass",
                       "-Command", "(Get-AuthenticodeSignature -LiteralPath $env:PCS_FILE).Status"],
                      timeout=90, env=dict(os.environ, PCS_FILE=str(path)))
        return r.stdout.strip() or "Unknown"
    except Exception:
        return "Unknown"


# ---- script analysis
def is_stdlib(name):
    if hasattr(sys, "stdlib_module_names"):
        return name in sys.stdlib_module_names or name in sys.builtin_module_names
    try:
        spec = importlib.util.find_spec(name)
    except Exception:
        return False
    if spec is None:
        return False
    if spec.origin in ("built-in", "frozen"):
        return True
    origin = spec.origin or ""
    return "site-packages" not in origin and origin.startswith(sysconfig.get_paths()["stdlib"])


def detect_packages(script):
    """Return (sorted pip packages, error or None)."""
    script = Path(script)
    pkgs, err = set(), None
    try:
        tree = ast.parse(script.read_text(encoding="utf-8-sig", errors="replace"))
        mods = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                mods.update(a.name.split(".")[0] for a in node.names)
            elif isinstance(node, ast.ImportFrom) and node.level == 0 and node.module:
                mods.add(node.module.split(".")[0])
        for m in mods:
            local = (script.parent / (m + ".py")).exists() or (script.parent / m).is_dir()
            if m == "__future__" or local or is_stdlib(m):
                continue
            pkgs.add(IMPORT_TO_PIP.get(m, m))
    except SyntaxError as e:
        err = str(e)
    req = script.parent / "requirements.txt"
    if req.is_file():
        for line in req.read_text(encoding="utf-8", errors="replace").splitlines():
            line = line.split("#")[0].strip()
            if line and not line.startswith("-"):
                pkgs.add(line)
    return sorted(pkgs, key=str.lower), err


