WIN_TARGETS = {
    "Windows 7": ((3, 8), "pyinstaller==5.13.2"),
    "Windows 8.1": ((3, 12), "pyinstaller"),
    "Windows 10": ((99, 0), "pyinstaller"),
    "Windows 11": ((99, 0), "pyinstaller"),
}
# PyInstaller 5.13 is the oldest maintained line and needs Python >= 3.7.
MIN_PY = (3, 7)
# Python 3.7/3.8 runtimes always get the 5.13.2 line (the last one that supports
# 3.7 and produces Windows 7 compatible bootloaders); newer Pythons get the latest.
LEGACY_PY_MAX = (3, 8)
LEGACY_PYI = "pyinstaller==5.13.2"


def pyinstaller_spec(ver):
    """pip requirement for PyInstaller that matches a Python version tuple such as (3, 8, 0).

    The choice depends ONLY on the interpreter that receives the package, never on the
    Windows target selected in the UI, so an old Python can not get an incompatible build.
    """
    return LEGACY_PYI if tuple(ver[:2]) <= LEGACY_PY_MAX else "pyinstaller"

