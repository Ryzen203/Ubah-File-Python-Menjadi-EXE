def hide_own_console():
    """Hide the black console when the app was started by double-clicking python.exe.

    The console is only hidden when every process attached to it is python/py, i.e.
    it was created just for us. A terminal you opened yourself (cmd, PowerShell) is
    left alone. Starting through "PyCompiler Studio.pyw" avoids the console entirely.
    """
    if os.name != "nt":
        return
    try:
        import ctypes
        k32, u32 = ctypes.windll.kernel32, ctypes.windll.user32
        k32.GetConsoleWindow.restype = ctypes.c_void_p
        k32.OpenProcess.restype = ctypes.c_void_p
        k32.OpenProcess.argtypes = [ctypes.c_uint, ctypes.c_int, ctypes.c_uint]
        k32.CloseHandle.argtypes = [ctypes.c_void_p]
        k32.QueryFullProcessImageNameW.argtypes = [ctypes.c_void_p, ctypes.c_uint, ctypes.c_wchar_p,
                                                   ctypes.POINTER(ctypes.c_uint)]
        u32.ShowWindow.argtypes = [ctypes.c_void_p, ctypes.c_int]
        hwnd = k32.GetConsoleWindow()
        if not hwnd:
            return
        pids = (ctypes.c_uint * 32)()
        n = k32.GetConsoleProcessList(pids, 32)
        if n == 0 or n > 32:
            return
        names = set()
        for pid in pids[:n]:
            h = k32.OpenProcess(0x1000, 0, pid)  # PROCESS_QUERY_LIMITED_INFORMATION
            if not h:
                return
            try:
                buf, size = ctypes.create_unicode_buffer(520), ctypes.c_uint(520)
                if not k32.QueryFullProcessImageNameW(h, 0, buf, ctypes.byref(size)):
                    return
                names.add(os.path.basename(buf.value).lower())
            finally:
                k32.CloseHandle(h)
        if names <= {"python.exe", "pythonw.exe", "py.exe", "pyw.exe"}:
            u32.ShowWindow(hwnd, 0)
    except Exception:
        pass


def quiet_run(cmd, timeout=None, **kw):
    """subprocess.run without a console window and without inheriting stdin.

    stdin must be redirected: under pythonw.exe there is no stdin and children
    would fail with "[WinError 6] The handle is invalid".
    """
    return subprocess.run([str(c) for c in cmd], capture_output=True, text=True, errors="replace",
                          timeout=timeout, stdin=subprocess.DEVNULL, creationflags=NO_WINDOW, **kw)


